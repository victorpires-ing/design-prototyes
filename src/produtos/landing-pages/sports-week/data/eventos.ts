import type { ModalidadeSlug } from "./modalidades";

/* Catálogo de eventos da Sports Week.

   Nome, cidade, estado, data, prazo de inscrição e imagem são REAIS: vieram do
   calendário público da Ticket Sports (`/api/events/list`), cinco eventos por
   modalidade. A imagem é servida direto do CDN deles.

   Sobre preço: a API não devolve valor, e um evento tem N modalidades com preços
   distintos. O que existe é o percentual de desconto, então o card anuncia
   "até X% OFF" e nunca um valor em reais.

   O que é simulação de campanha, e está marcado como tal: `descontoMaximo`,
   `destaque`, `relampago`, `gratuito` e `esgotado`. */

export interface Evento {
    id: string;
    titulo: string;
    modalidade: ModalidadeSlug;
    /** ISO, usado para ordenar. */
    data: string;
    dataLabel: string;
    /** Prazo final de inscrição. É a informação de urgência que o card carrega. */
    inscricoesAte: string;
    inscricoesAteLabel: string;
    cidade: string;
    uf: string;
    /** Capa do evento, servida pelo CDN da Ticket Sports. */
    imagem: string;
    /** Simulado: maior desconto entre as modalidades. Sempre anunciado como "até". */
    descontoMaximo: number;
    /** Simulado: inscrição de cortesia. */
    gratuito?: boolean;
    /** Simulado: entra no carrossel de destaques da home. */
    destaque?: boolean;
    /** Simulado: oferta-relâmpago, só vale no dia. */
    relampago?: boolean;
    /** Simulado: existe um só, para a interface poder mostrar o estado. */
    esgotado?: boolean;
}

